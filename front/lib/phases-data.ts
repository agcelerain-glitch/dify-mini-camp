export const PHASES: Phase[] = [PHASE1, PHASE2, PHASE3, PHASE4, PHASE5];

export function getPhase(id: number): Phase | undefined {
  return PHASES.find((p) => p.id === id);
}

export function getLevel(phaseId: number, levelId: number) {
  return getPhase(phaseId)?.levels.find((l) => l.id === levelId);
}

export function getTotalLevels(phaseId: number): number {
  return getPhase(phaseId)?.levels.length ?? 0;
}

export function getTotalPages(phaseId: number, levelId: number): number {
  return getLevel(phaseId, levelId)?.pages.length ?? 0;
}
